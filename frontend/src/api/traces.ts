import { validateTrace, type Trace } from '../types/vep';

export interface TraceMetadata {
  id: string;
  label: string;
  group: 'dsa' | 'python' | 'java' | 'backend' | string;
}

export interface TracesResponse {
  traces: TraceMetadata[];
}

export interface TraceResponse {
  trace: Trace;
}

export interface ApiErrorResponse {
  error?: string;
  message?: string;
}

export interface CustomLinearSearchInput {
  values: number[];
  target: number;
}

/**
 * Fetches the list of all registered algorithm traces from the backend.
 *
 * @param signal Optional AbortSignal for request cancellation
 * @returns Array of algorithm metadata items
 */
export async function fetchTraces(signal?: AbortSignal): Promise<TraceMetadata[]> {
  let res: Response;
  try {
    res = await fetch('/api/traces', { signal });
  } catch (error) {
    if (error instanceof Error && error.name === 'AbortError') {
      throw error;
    }
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(
      `Failed to connect to backend server: ${detail}. Ensure backend is running.`
    );
  }

  if (!res.ok) {
    let errorMessage = `HTTP ${res.status} ${res.statusText}`.trim();
    try {
      const errData = (await res.json()) as ApiErrorResponse;
      if (errData?.message) {
        errorMessage = errData.message;
      } else if (errData?.error) {
        errorMessage = errData.error;
      }
    } catch {
      // Ignore json parse error and keep default status text
    }
    throw new Error(`Failed to fetch traces: ${errorMessage}`);
  }

  let data: unknown;
  try {
    data = await res.json();
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(`Failed to parse response from /api/traces as JSON: ${detail}`);
  }

  if (
    !data ||
    typeof data !== 'object' ||
    !('traces' in data) ||
    !Array.isArray((data as TracesResponse).traces)
  ) {
    throw new Error('Invalid response from /api/traces: expected { traces: Array }');
  }

  const rawList = (data as TracesResponse).traces;
  for (let i = 0; i < rawList.length; i++) {
    const item = rawList[i];
    if (
      !item ||
      typeof item !== 'object' ||
      typeof item.id !== 'string' ||
      typeof item.label !== 'string'
    ) {
      throw new Error(
        `Invalid trace metadata at index ${i}: expected id and label strings`
      );
    }
  }

  return rawList;
}

/**
 * Fetches a single algorithm trace by ID and validates it against the VEP schema.
 *
 * @param id Algorithm trace ID (canonical ID or supported alias)
 * @param signal Optional AbortSignal for request cancellation
 * @returns Validated Trace object
 */
export async function fetchTraceById(id: string, signal?: AbortSignal): Promise<Trace> {
  if (!id || typeof id !== 'string' || id.trim() === '') {
    throw new Error('Trace ID must be a non-empty string');
  }

  let res: Response;
  try {
    res = await fetch(`/api/traces/${encodeURIComponent(id)}`, { signal });
  } catch (error) {
    if (error instanceof Error && error.name === 'AbortError') {
      throw error;
    }
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(
      `Failed to connect to backend server: ${detail}. Ensure backend is running.`
    );
  }

  if (!res.ok) {
    let errorMessage = `HTTP ${res.status} ${res.statusText}`.trim();
    try {
      const errData = (await res.json()) as ApiErrorResponse;
      if (errData?.message) {
        errorMessage = errData.message;
      } else if (errData?.error) {
        errorMessage = errData.error;
      }
    } catch {
      // Ignore json parse error and keep default status text
    }
    throw new Error(`Failed to fetch trace "${id}": ${errorMessage}`);
  }

  let data: unknown;
  try {
    data = await res.json();
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(`Failed to parse response from /api/traces/${id} as JSON: ${detail}`);
  }

  if (!data || typeof data !== 'object' || !('trace' in data)) {
    throw new Error(`Invalid response from /api/traces/${id}: expected { trace: Object }`);
  }

  const rawTrace = (data as TraceResponse).trace;
  try {
    return validateTrace(rawTrace);
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(`Trace validation failed for "${id}": ${detail}`);
  }
}

